struct DwcDdrPhy {
    apb_base: usize,
    dram_type: DramType,
}

impl DwcDdrPhy {
    // PHY APB half-word offsets
    const MICRO_CONT_MUX_SEL: usize = 0x00D0000;
    const IMEM_OFF: usize = 0x0050000;
    const DMEM_OFF: usize = 0x0058000;
    const DCT_WRITE_PROT: usize = 0x00D0031;
    const UCT_WRITE_PROT: usize = 0x00C0033;
    const MICRO_STALL_TO_ARESET: usize = 0x00D0099;
    const APBONLY0: usize = 0x0020089;
    const UCT_SHADOW_REGS: usize = 0x00D0004;
    const UCT_WRITE_ONLY_SHADOW: usize = 0x00D0032;
    const UCT_DATA_WRITE_ONLY_SHADOW: usize = 0x00D0034;
    const DWC_PHY_DDR4_MB_RESULT: usize = 0x005800A;
    const DWC_PHY_DDR5_MB_RESULT: usize = 0x0058007;
    const UCTWRITEPROT_SHADOW_BIT: u16 = 1 << 0;
    const MB_TRAIN_SUCCESS: u16 = 0x0007;
    const MB_TRAIN_FAIL: u16 = 0x00FF;
    const MB_START_STREAM: u16 = 0x0008;

    fn new(base: usize, dram: DramType) -> Self {
        Self {
            apb_base: base,
            dram_type: dram,
        }
    }

    // half-word offset → byte address within PHY APB
    #[inline(always)]
    fn a16(&self, off_half: usize) -> usize {
        self.apb_base + (off_half << 1)
    }

    // ── Raw volatile I/O — all unsafe fn, zero unsafe{} inside ───────────
    #[inline(always)]
    unsafe fn wr16(&self, addr: usize, val: u16) {
        core::ptr::write_volatile(addr as *mut u16, val);
    }

    #[inline(always)]
    unsafe fn rd16(&self, addr: usize) -> u16 {
        core::ptr::read_volatile(addr as *const u16)
    }

    // Absolute MMIO 32-bit access (SCU, address-translation register, etc.)
    #[inline(always)]
    unsafe fn wr32(addr: usize, val: u32) {
        core::ptr::write_volatile(addr as *mut u32, val);
    }

    #[inline(always)]
    unsafe fn rd32(&self, addr: usize) -> u32 {
        core::ptr::read_volatile(addr as *const u32)
    }

    fn apply_sequence(&self, seq: &[(usize, u16)]) {
        unsafe {
            for &(off, val) in seq {
                self.wr16(self.a16(off), val);
            }
        }
    }

    fn apply_sequence32(&self, seq: &[(usize, u32)]) {
        unsafe {
            for &(off, val) in seq {
                Self::wr32(self.a16(off), val);
            }
        }
    }

    /// Copy PHY IMEM firmware from the boot-device-supplied address into PHY IMEM space.
    /// Safe fn — unsafe{} is contained here; callers need no unsafe block.
    fn program_imem_phy_image(&self, addr: u64, len_bytes: u32) {
        unsafe {
            /*
             * 1. Enable access to the internal CSRs by setting the MicroContMuxSel CSR to 0.
             *    This allows the memory controller unrestricted access to the configuration CSRs.
             */
            self.wr16(self.a16(Self::MICRO_CONT_MUX_SEL), 0);

            /*
             * 2. Copy the IMEM code to the PHY IMEM address (0x13xx_xxxx,
             *    MCU view: 0x33xx_xxxx).
             */
            let src = addr as *const u32;
            let dst = (0x3300_0000usize + Self::IMEM_OFF * 2) as *mut u32;

            caliptra_mcu_romtime::println!(
                "[mcu-runtime] Copying IMEM from 0x{:08X} to 0x{:08X}, length {} bytes...",
                addr,
                0x3300_0000usize + Self::IMEM_OFF * 2,
                len_bytes,
            );
            copy_nonoverlapping(src, dst, len_bytes as usize);

            /*
             * 3. Isolate the APB access from the internal CSRs by setting MicroContMuxSel to 1.
             *    This allows the firmware unrestricted access to the configuration CSRs.
             */
            self.wr16(self.a16(Self::MICRO_CONT_MUX_SEL), 1);
        }
    }

    fn program_dmem_phy_image(&self, image: u64, len_bytes: u32, seq: &[(usize, u32)]) {
        unsafe {
            self.wr16(self.a16(Self::MICRO_CONT_MUX_SEL), 0);

            let src = image as *const u32;
            let dst = 0x3300_0000 + Self::DMEM_OFF * 2;
            caliptra_mcu_romtime::println!(
                "[mcu-runtime] Copying DMEM from 0x{:08X} to 0x{:08X}, length {} bytes...",
                image,
                0x3300_0000usize + Self::DMEM_OFF * 2,
                len_bytes,
            );
            copy_nonoverlapping(src as *const u32, dst as *mut u32, len_bytes as usize);

            self.apply_sequence32(seq);

            self.wr16(self.a16(Self::MICRO_CONT_MUX_SEL), 1);
        }
    }

    fn mailbox_init(&self) {
        unsafe {
            self.wr16(self.a16(Self::DCT_WRITE_PROT), 1);
            self.wr16(self.a16(Self::UCT_WRITE_PROT), 1);
        }
    }

    fn read_msg_block_u16(&self, addr_half: usize) -> u16 {
        unsafe {
            let even = (addr_half >> 1) << 1;
            let d32 = self.rd32(self.a16(even));
            if (addr_half & 1) != 0 {
                ((d32 >> 16) & 0xFFFF) as u16
            } else {
                (d32 & 0xFFFF) as u16
            }
        }
    }

    fn mailbox_get(&self, stream: bool) -> u32 {
        unsafe {
            while (self.rd16(self.a16(Self::UCT_SHADOW_REGS)) & Self::UCTWRITEPROT_SHADOW_BIT) != 0
            {
            }
            let mut mail = (self.rd16(self.a16(Self::UCT_WRITE_ONLY_SHADOW)) & 0xFFFF) as u32;
            if stream {
                let d = (self.rd16(self.a16(Self::UCT_DATA_WRITE_ONLY_SHADOW)) & 0xFFFF) as u32;
                mail |= d << 16;
            }
            self.wr16(self.a16(Self::DCT_WRITE_PROT), 0);
            while (self.rd16(self.a16(Self::UCT_SHADOW_REGS)) & Self::UCTWRITEPROT_SHADOW_BIT) == 0
            {
            }
            self.wr16(self.a16(Self::DCT_WRITE_PROT), 1);
            mail
        }
    }

    fn wait_fw_done(&self, show_stream: bool) -> Result<(), ()> {
        let mut code: u16 = 0;
        caliptra_mcu_romtime::println!("[mcu-runtime] Wait for training completion...");
        while code != Self::MB_TRAIN_SUCCESS && code != Self::MB_TRAIN_FAIL {
            let m = self.mailbox_get(false);
            code = (m & 0xFFFF) as u16;
            if show_stream && code == Self::MB_START_STREAM {
                let hdr = self.mailbox_get(true);
                let n = (hdr & 0xFFFF) as usize;
                for _ in 0..n {
                    let _ = self.mailbox_get(true);
                }
            }
        }
        if code == Self::MB_TRAIN_SUCCESS {
            Ok(())
        } else {
            Err(())
        }
    }

    fn report_training_result(&self, _train_2d: bool) {
        caliptra_mcu_romtime::println!("[mcu-runtime] DDR training result:");

        let result = match self.dram_type {
            DramType::Ddr4 => self.read_msg_block_u16(Self::DWC_PHY_DDR4_MB_RESULT),
            DramType::Ddr5 => self.read_msg_block_u16(Self::DWC_PHY_DDR5_MB_RESULT),
        };

        caliptra_mcu_romtime::println!(
            "  {}D Training result code: 0x{:04X} ({})",
            if _train_2d { 2 } else { 1 },
            result,
            if result != 0 {
                "FAIL"
            } else if result == 0 {
                "SUCCESS"
            } else {
                "UNKNOWN"
            }
        );
        let _ = result;
    }

    fn run_training_and_get_results(&self, train_2d: bool) -> Result<(), ()> {
        caliptra_mcu_romtime::println!("[mcu-runtime] Run training and enter mission mode...");

        unsafe {
            self.apply_sequence(EXEC_TRAINING_FW);
            self.wait_fw_done(false)?;

            // Halt the microcontroller.
            self.wr16(self.a16(Self::MICRO_STALL_TO_ARESET), 1);
            self.wr16(self.a16(Self::APBONLY0), 0);

            // Read the Message Block results.
            self.wr16(self.a16(Self::MICRO_CONT_MUX_SEL), 0);
            self.report_training_result(train_2d);
            self.wr16(self.a16(Self::MICRO_CONT_MUX_SEL), 1);
        }

        Ok(())
    }
}

